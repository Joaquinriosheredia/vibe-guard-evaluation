"""The optional AI review (PREREGISTRATION.md, "Optional AI review"): comparison only, it never decides.

  python3 scripts/ai_compare.py seal <OUT>
      <OUT> is a `vibe-guard review` output directory OUTSIDE the repository (review-a.json and, if
      the refuter ran, review-b.json). Refuses once REVIEW-SHEET.md exists (the review must be sealed
      before the sheet reaches Joaquín), when ai-review.sha256 exists, or when the entries are not
      exactly the review-set IDs; writes ai-review.sha256 and prints no verdict.
  python3 scripts/ai_compare.py compare <OUT>
      only after audit-joaquin.json and audit-joaquin.sha256 match: checks the files against
      ai-review.sha256, then writes ai-comparison.json and AI-COMPARISON.md: agreement with Joaquín
      per configuration (A; A+B = B's final verdict) and language, Wilson 95 %, Cohen's kappa, the
      disagreeing IDs, and the informative threshold (>= 95 %). An invalid or missing answer counts
      as disagreement.
"""
import hashlib
import json
import sys
from collections import Counter
from pathlib import Path

DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
from evaluate import wilson  # noqa: E402

SEALED = "ai-review.sha256"
FILES = {"A": "review-a.json", "A+B": "review-b.json"}
THRESHOLD = 0.95  # informative only (PREREGISTRATION.md)
LANGS = {"java": "J", "python": "P"}


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def review_ids():
    return [f["id"] for f in json.loads((DIR / "review-set.json").read_text())["findings"]]


def ai_verdicts(data, ids):
    """vibe-guard review output -> {id: "TP"|"FP"|"U"|None}; None = invalid answer. Refuses other IDs."""
    entries = {e["id"]: e for e in data["entries"]}
    if set(entries) != set(ids):
        raise ValueError(f"entries are not exactly the review set: missing {sorted(set(ids) - set(entries))}, extra {sorted(set(entries) - set(ids))}")
    return {i: (entries[i].get("verdict") if entries[i].get("valid") and entries[i].get("verdict") in ("TP", "FP", "U") else None) for i in ids}


def kappa(pairs):
    """Cohen's kappa over the categories present (an invalid AI answer is its own category)."""
    n = len(pairs)
    if n == 0:
        return None
    po = sum(a == b for a, b in pairs) / n
    ca, cb = Counter(a for a, _ in pairs), Counter(b for _, b in pairs)
    pe = sum(ca[c] * cb[c] for c in set(ca) | set(cb)) / (n * n)
    return None if pe == 1 else round((po - pe) / (1 - pe), 4)


def compare(ai, joaquin, ids):
    """ai: {id: verdict|None}; joaquin: {id: verdict}. Per language and in total."""
    out = {}
    for lang, prefix in (*LANGS.items(), ("all", "")):
        lids = [i for i in ids if i.startswith(prefix)]
        agree = [i for i in lids if ai[i] == joaquin[i]]
        n = len(lids)
        rate = round(len(agree) / n, 4) if n else None
        out[lang] = {"n": n, "agree": len(agree), "rate": rate, "rateCI95": wilson(len(agree), n),
                     "cohenKappa": kappa([(ai[i] or "invalid", joaquin[i]) for i in lids]),
                     "invalid": [i for i in lids if ai[i] is None],
                     "disagreeing": [i for i in lids if ai[i] != joaquin[i]],
                     "meetsInformativeThreshold": rate is not None and rate >= THRESHOLD}
    return out


def render(result):
    md = ["# AI review vs Joaquín — test-corpus-4 (comparison only, never decides)", "",
          "Generated by `scripts/ai_compare.py compare` after `audit-joaquin.json` and the sealed AI review matched their committed sha256.",
          f"Informative threshold: agreement ≥ {THRESHOLD:.0%} per language. Meeting it does **not** make the AI review a measurement method (`PREREGISTRATION.md`).", "",
          "| configuration | language | n | agree | agreement | Wilson 95 % | Cohen's kappa | invalid | ≥ 95 % |", "|---|---|---|---|---|---|---|---|---|"]
    for cfg, by in result.items():
        for lang, c in by.items():
            ci = "—" if c["rateCI95"] is None else f"{c['rateCI95'][0]}–{c['rateCI95'][1]}"
            md.append(f"| {cfg} | {lang} | {c['n']} | {c['agree']} | {c['rate']} | {ci} | {c['cohenKappa']} | {len(c['invalid'])} | {'yes' if c['meetsInformativeThreshold'] else 'no'} |")
    for cfg, by in result.items():
        md += ["", f"## Disagreeing IDs — {cfg}", ""] + ([f"- [{i}](cards/{i}.md)" for i in by["all"]["disagreeing"]] or ["(none)"])
    return "\n".join(md) + "\n"


def main(argv):
    if len(argv) != 2 or argv[0] not in ("seal", "compare"):
        raise SystemExit(__doc__)
    out = Path(argv[1]).resolve()
    if DIR.parent in out.parents or out == DIR.parent:
        raise SystemExit(f"{out} is inside the repository: the AI review is kept outside until Joaquín's verdicts are committed")
    ids = review_ids()
    present = [cfg for cfg, f in FILES.items() if (out / f).exists()]
    if "A" not in present:
        raise SystemExit(f"{out / FILES['A']} missing")
    if argv[0] == "seal":
        if (DIR / "REVIEW-SHEET.md").exists():
            raise SystemExit("REVIEW-SHEET.md exists: the AI review had to be sealed before the sheet was delivered; it is not run for test-corpus-4")
        if (DIR / SEALED).exists():
            raise SystemExit(f"{SEALED} exists")
        for cfg in present:
            try:
                ai_verdicts(json.loads((out / FILES[cfg]).read_text()), ids)
            except ValueError as e:
                raise SystemExit(f"{FILES[cfg]}: {e}")
        (DIR / SEALED).write_text("".join(f"{sha256(out / FILES[cfg])}  {FILES[cfg]}\n" for cfg in present))
        print(f"{SEALED}: {', '.join(FILES[c] for c in present)} sealed (no verdict shown)")
        return
    audit, audit_sha = DIR / "audit-joaquin.json", DIR / "audit-joaquin.sha256"
    if not audit.exists() or not audit_sha.exists() or sha256(audit) != audit_sha.read_text().split()[0]:
        raise SystemExit("audit-joaquin.json and its matching audit-joaquin.sha256 must be committed first")
    sealed = dict(reversed(line.split()) for line in (DIR / SEALED).read_text().splitlines() if line.strip())
    for cfg in present:
        if sha256(out / FILES[cfg]) != sealed.get(FILES[cfg]):
            raise SystemExit(f"{FILES[cfg]} does not match {SEALED}")
    if set(sealed) != {FILES[c] for c in present}:
        raise SystemExit(f"{SEALED} seals {sorted(sealed)}, found {[FILES[c] for c in present]}")
    joaquin = {v["id"]: v["verdict"] for v in json.loads(audit.read_text())["verdicts"]}
    result = {cfg: compare(ai_verdicts(json.loads((out / FILES[cfg]).read_text()), ids), joaquin, ids) for cfg in present}
    (DIR / "ai-comparison.json").write_text(json.dumps({"threshold": THRESHOLD, "decides": False, "configurations": result}, indent=2) + "\n")
    (DIR / "AI-COMPARISON.md").write_text(render(result))
    for cfg, by in result.items():
        print(cfg, {lang: (c["agree"], c["n"], c["rate"]) for lang, c in by.items()})


if __name__ == "__main__":
    main(sys.argv[1:])
