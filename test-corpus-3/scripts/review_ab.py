"""Review A against review B (PREREGISTRATION.md, "Review method").

  python3 scripts/review_ab.py seal A|B <PRIVATE>
      merges <PRIVATE>/a-batch-*.json (or b-batch-*.json) into <PRIVATE>/audit-claude-A.json
      (or -B), outside the repository, and writes audit-claude-A.sha256 (or -B); fails if the
      IDs are not exactly the review set in order or any entry is invalid; prints no verdict
      counts. Both are sealed before either is opened.
  python3 scripts/review_ab.py open <audit-claude-A.json> <audit-claude-B.json>
      checks both files against their committed sha256, then writes REVIEW-AB.md: counts,
      the disagreeing IDs and the audit sample of 20 agreeing IDs (random.Random(20261104)),
      IDs only, never a verdict
"""
import hashlib
import json
import random
import sys
from pathlib import Path

DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
from evaluate import kappa  # noqa: E402

VERDICTS = ("TP", "FP", "U")
SEED_AUDIT = 20261104
AUDIT_N = 20
# PREREGISTRATION.md: A = Claude Opus 5.5, B = Claude Sonnet 5.5.
REVIEWERS = {"A": "Claude (review A, claude-opus-5-5)", "B": "Claude (review B, claude-sonnet-5-5)"}


def review_ids():
    return [f["id"] for f in json.loads((DIR / "review-set.json").read_text())["findings"]]


def validate(verdicts, ids):
    """Raises ValueError listing every problem; returns the verdicts unchanged."""
    problems = []
    got = [v.get("id") for v in verdicts]
    if got != list(ids):
        problems.append(f"the IDs are not exactly the review set in order ({len(got)} vs {len(ids)})")
    for v in verdicts:
        if v.get("verdict") not in VERDICTS:
            problems.append(f"{v.get('id')}: verdict is not TP, FP or U")
        if not str(v.get("reason", "")).strip():
            problems.append(f"{v.get('id')}: reason missing")
        if not isinstance(v.get("overstated"), bool):
            problems.append(f"{v.get('id')}: overstated is not true/false")
    if problems:
        raise ValueError("\n".join(problems))
    return verdicts


def merge_batches(batches, ids):
    """Batch files (in batch order) -> one verdict list in review-set order."""
    by_id = {}
    for b in batches:
        for v in b["verdicts"]:
            if v.get("id") in by_id:
                raise ValueError(f"{v.get('id')}: appears twice")
            by_id[v.get("id")] = {k: v.get(k) for k in ("id", "verdict", "reason", "overstated")}
    if set(by_id) != set(ids):
        raise ValueError(f"the batches do not cover exactly the review set ({len(by_id)} vs {len(ids)})")
    return validate([by_id[i] for i in ids], ids)


def compare(a, b, ids):
    """Agreement on the `verdict` field. Returns counts per language and the disagreeing IDs."""
    va, vb = {v["id"]: v["verdict"] for v in a}, {v["id"]: v["verdict"] for v in b}
    out = {}
    for lang, prefix in (("java", "J"), ("python", "P"), ("all", "")):
        lids = [i for i in ids if i.startswith(prefix)]
        k = kappa([(va[i], vb[i]) for i in lids])
        dis = [i for i in lids if va[i] != vb[i]]
        out[lang] = {"n": len(lids), "agree": len(lids) - len(dis), "disagree": len(dis),
                     "raw": k["raw"], "cohenKappa": k["cohenKappa"], "disagreeing": dis}
    return out


def audit_sample(agreeing):
    """random.Random(20261104).sample(agreeing in review-set order, 20), listed in review-set order."""
    picked = set(random.Random(SEED_AUDIT).sample(list(agreeing), AUDIT_N))
    return [i for i in agreeing if i in picked]


def render(cmp, sample):
    md = ["# Review A vs review B — test-corpus-3 (`PREREGISTRATION.md`, \"Review method\")", "",
          "Generated by `scripts/review_ab.py open` after both files matched their committed sha256.",
          "**IDs only: no verdict of A or B is shown here.** Agreement is on the verdict (TP/FP/U).", "",
          "| | n | agree | disagree | raw agreement | Cohen's kappa |", "|---|---|---|---|---|---|"]
    for lang in ("java", "python", "all"):
        c = cmp[lang]
        md.append(f"| {lang} | {c['n']} | {c['agree']} | {c['disagree']} | {c['raw']} | {c['cohenKappa']} |")
    dis = cmp["all"]["disagreeing"]
    md += ["", f"## Disagreements ({len(dis)}): Joaquín decides each from its card", ""]
    md += [f"- [{i}](cards/{i}.md)" for i in dis] or ["(none)"]
    md += ["", f"## Audit sample ({len(sample)} of the agreeing, `random.Random({SEED_AUDIT})`): Joaquín reviews without seeing A or B", ""]
    md += [f"- [{i}](cards/{i}.md)" for i in sample]
    return "\n".join(md) + "\n"


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def committed(name):
    return (DIR / name).read_text().split()[0]


def main(argv):
    ids = review_ids()
    if argv[:1] == ["seal"] and len(argv) == 3 and argv[1] in REVIEWERS:
        who, priv = argv[1], Path(argv[2])
        out, sha = priv / f"audit-claude-{who}.json", DIR / f"audit-claude-{who}.sha256"
        if out.exists() or sha.exists():
            raise SystemExit(f"audit-claude-{who}.json or audit-claude-{who}.sha256 exists")
        files = sorted(priv.glob(f"{who.lower()}-batch-*.json"), key=lambda p: int(p.stem.rsplit("-", 1)[1]))
        try:
            verdicts = merge_batches([json.loads(p.read_text()) for p in files], ids)
        except ValueError as e:
            raise SystemExit(f"review {who} is not complete:\n{e}")
        out.write_text(json.dumps({"reviewer": REVIEWERS[who], "verdicts": verdicts}, indent=2, ensure_ascii=False) + "\n")
        sha.write_text(f"{sha256(out)}  audit-claude-{who}.json\n")
        print(f"audit-claude-{who}.json: {len(verdicts)} verdicts from {len(files)} batches; sha256 {sha256(out)}")
    elif argv[:1] == ["open"] and len(argv) == 3:
        for path, name in ((argv[1], "audit-claude-A.sha256"), (argv[2], "audit-claude-B.sha256")):
            if sha256(path) != committed(name):
                raise SystemExit(f"{path} does not match {name}")
        out = DIR / "REVIEW-AB.md"
        if out.exists():
            raise SystemExit("REVIEW-AB.md exists")
        a = validate(json.loads(Path(argv[1]).read_text())["verdicts"], ids)
        b = validate(json.loads(Path(argv[2]).read_text())["verdicts"], ids)
        cmp = compare(a, b, ids)
        dis = set(cmp["all"]["disagreeing"])
        sample = audit_sample([i for i in ids if i not in dis])
        out.write_text(render(cmp, sample))
        for lang in ("java", "python", "all"):
            c = cmp[lang]
            print(f"{lang}: n {c['n']}, agree {c['agree']}, disagree {c['disagree']}, raw {c['raw']}, kappa {c['cohenKappa']}")
        print(f"audit sample: {len(sample)}")
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main(sys.argv[1:])
